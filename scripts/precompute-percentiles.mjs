import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { evaluateHeuristic } from "../src/parser.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(__dirname, "..");
const OUT_FILE = path.join(PROJECT_ROOT, "src", "percentile-tables.js");
const BASIS = 1000; // 0.001% step

const VARIANT_HAND_SIZE = {
  plo4: 4,
  plo5: 5
};

function nChooseK(n, k) {
  if (k < 0 || k > n) return 0;
  if (k === 0 || k === n) return 1;
  const kk = Math.min(k, n - k);
  let out = 1;
  for (let i = 1; i <= kk; i++) out = (out * (n - kk + i)) / i;
  return Math.round(out);
}

function enumerateScoreKeys(variant, handSize) {
  const total = nChooseK(52, handSize);
  const scoreKeys = new Int32Array(total);
  const hand = new Array(handSize).fill(0);
  let idx = 0;

  function rec(start, depth) {
    if (depth === handSize) {
      scoreKeys[idx++] = Math.round(evaluateHeuristic(hand, variant) * 10);
      return;
    }
    for (let c = start; c <= 52 - (handSize - depth); c++) {
      hand[depth] = c;
      rec(c + 1, depth + 1);
    }
  }

  rec(0, 0);
  return scoreKeys;
}

function buildSortedOrderByScore(scoreKeys) {
  const total = scoreKeys.length;
  let min = Number.POSITIVE_INFINITY;
  let max = Number.NEGATIVE_INFINITY;
  for (let i = 0; i < total; i++) {
    const v = scoreKeys[i];
    if (v < min) min = v;
    if (v > max) max = v;
  }
  const span = max - min + 1;
  const counts = new Uint32Array(span);
  for (let i = 0; i < total; i++) counts[scoreKeys[i] - min]++;

  const starts = new Uint32Array(span);
  let cursor = 0;
  for (let key = max; key >= min; key--) {
    const idx = key - min;
    starts[idx] = cursor;
    cursor += counts[idx];
  }

  const writePos = starts.slice();
  const sortedRanks = new Uint32Array(total);
  // rank asc within equal score keys for deterministic exact tie-breaking.
  for (let rank = 0; rank < total; rank++) {
    const idx = scoreKeys[rank] - min;
    const pos = writePos[idx]++;
    sortedRanks[pos] = rank;
  }
  return sortedRanks;
}

function buildTopCutoffs(scoreKeys, sortedRanks) {
  const total = scoreKeys.length;
  const steps = 100 * BASIS;
  const topScoreKeys = new Int32Array(steps + 1);
  const topRanks = new Int32Array(steps + 1);
  for (let i = 0; i <= steps; i++) {
    const count = Math.floor((i / steps) * total);
    if (count <= 0) {
      topScoreKeys[i] = -2147483648;
      topRanks[i] = -1;
      continue;
    }
    const boundaryPos = Math.min(total - 1, count - 1);
    const rank = sortedRanks[boundaryPos];
    topRanks[i] = rank;
    topScoreKeys[i] = scoreKeys[rank];
  }
  return {
    topScoreKeys: Array.from(topScoreKeys),
    topRanks: Array.from(topRanks)
  };
}

function parseVariants(args) {
  const wanted = new Set();
  for (const a of args) {
    for (const tok of String(a).split(",")) {
      const v = tok.trim().toLowerCase();
      if (v) wanted.add(v);
    }
  }
  if (!wanted.size) {
    return Object.keys(VARIANT_HAND_SIZE);
  }
  return [...wanted].filter((v) => Object.hasOwn(VARIANT_HAND_SIZE, v));
}

function buildTables(variants) {
  const tables = {};
  for (const variant of variants) {
    const handSize = VARIANT_HAND_SIZE[variant];
    const t0 = Date.now();
    process.stderr.write(`[precompute] ${variant}: enumerating C(52,${handSize}) ...\n`);
    const scoreKeys = enumerateScoreKeys(variant, handSize);
    process.stderr.write(`[precompute] ${variant}: ordering ${scoreKeys.length.toLocaleString()} combos ...\n`);
    const sortedRanks = buildSortedOrderByScore(scoreKeys);
    process.stderr.write(`[precompute] ${variant}: building exact top-% cutoffs ...\n`);
    const cutoffs = buildTopCutoffs(scoreKeys, sortedRanks);
    const elapsed = ((Date.now() - t0) / 1000).toFixed(2);
    process.stderr.write(`[precompute] ${variant}: done in ${elapsed}s\n`);
    tables[variant] = {
      basis: BASIS,
      sampleSize: scoreKeys.length,
      source: "heuristic-full-enumeration-exact-cutoff",
      generatedAt: new Date().toISOString(),
      ...cutoffs
    };
  }
  return tables;
}

function writeModule(tables) {
  const text = `// Auto-generated by scripts/precompute-percentiles.mjs.\n` +
    `// Do not edit manually.\n\n` +
    `export const PRECOMPUTED_PERCENTILE_TABLES = ${JSON.stringify(tables, null, 2)};\n`;
  fs.writeFileSync(OUT_FILE, text, "utf8");
}

function main() {
  const variants = parseVariants(process.argv.slice(2));
  if (!variants.length) {
    throw new Error("No supported variants provided. Use: plo4, plo5");
  }
  const tables = buildTables(variants);
  writeModule(tables);
  process.stderr.write(`[precompute] wrote ${OUT_FILE}\n`);
}

main();
